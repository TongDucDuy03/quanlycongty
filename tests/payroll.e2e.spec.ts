test('payroll tabs fit mobile and retain dark theme without browser errors', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#payroll')
  await expect(page.getByRole('heading', { name: 'Nhân sự & tiền lương.', exact: true })).toBeVisible()
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') {
      await page.getByRole('button', { name: 'Chuyển chế độ tối' }).click()
      await page.reload()
    }
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    for (const [id, label] of [['employees', 'Nhân sự'], ['attendance', 'Chấm công'], ['salary', 'Bảng lương'], ['settings', 'Cấu hình lương']]) {
      await page.getByRole('tab', { name: label, exact: true }).click()
      expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth), `${theme}/${label}`).toBeLessThanOrEqual(1)
      await page.screenshot({ path: testInfo.outputPath(`payroll-${id}-${theme}.png`), fullPage: true })
    }
  }
  expect(errors).toEqual([])
})

test('legacy backup keeps existing operations and opens an empty payroll workspace', async ({ page }) => {
  await page.goto('/#settings')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Sao lưu JSON' }).click()
  const download = await downloadPromise
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  const malformed = structuredClone(backup)
  malformed.payroll.attendance.push({ ...malformed.payroll.attendance[0], id: 'duplicate-worker-date-QA' })
  await page.locator('input[type=file]').setInputFiles({ name: 'duplicate-attendance.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(malformed)) })
  await expect(page.getByRole('alert')).toContainText('không đúng định dạng')
  delete backup.payroll
  backup.customers[0].name = 'Khách giữ nguyên khi thêm nhân sự QA'
  page.once('dialog', dialog => dialog.accept())
  await page.locator('input[type=file]').setInputFiles({ name: 'legacy-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  await expect(page.locator('.toast')).toContainText('Đã khôi phục dữ liệu')
  await page.goto('/#payroll')
  await expect(page.getByRole('button', { name: 'Thêm nhân viên', exact: true })).toBeVisible()
  expect((await stored(page)).customers[0].name).toBe(backup.customers[0].name)
  expect((await stored(page)).payroll?.employees ?? []).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: 'Thêm nhân viên', exact: true })).toBeVisible()
})

test('salary, attendance, allowances, insurance and adjustments survive locking and reopening', async ({ page }, testInfo) => {
  const name = 'Công nhân tính lương QA'
  const month = '2030-01'
  await page.goto('/#payroll')
  await page.getByRole('tab', { name: 'Cấu hình lương', exact: true }).click()
  await page.getByLabel(/^Bảo hiểm người lao động/).fill('10')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm loại phụ cấp', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Tên phụ cấp', { exact: true }).fill('Ăn ca QA')
  await dialog.getByLabel('Cách tính phụ cấp').selectOption('workday')
  await dialog.getByLabel('Mức tiền gợi ý (₫)').fill('60000')
  await dialog.getByRole('button', { name: 'Lưu phụ cấp', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('tab', { name: 'Nhân sự', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm nhân viên', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Họ và tên', { exact: true }).fill(name)
  await dialog.getByLabel(/^Mức lương \(/).fill('26000000')
  await dialog.getByLabel(/^Lương đóng bảo hiểm/).fill('1000000')
  await dialog.getByLabel('Ngày vào làm', { exact: true }).fill('2030-01-01')
  await dialog.getByRole('checkbox', { name: /Ăn ca QA/ }).check()
  await dialog.getByRole('button', { name: 'Lưu nhân viên', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('tab', { name: 'Chấm công', exact: true }).click()
  await page.getByRole('button', { name: 'Theo ngày', exact: true }).click()
  await page.getByLabel('Ngày chấm công', { exact: true }).fill(`${month}-02`)
  await page.getByRole('button', { name: `Chấm công ${name}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Giờ làm bình thường').fill('9')
  await dialog.getByRole('button', { name: 'Lưu chấm công', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Chấm công không hợp lệ')
  await dialog.getByLabel('Giờ làm bình thường').fill('8')
  await dialog.getByLabel('Giờ tăng ca ngày thường').fill('2')
  await dialog.getByRole('button', { name: 'Lưu chấm công', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  // Saving the same worker/date replaces the entry, rather than double-paying it.
  await page.getByRole('button', { name: `Chấm công ${name}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ghi chú', { exact: true }).fill('Đã kiểm tra ngày công QA')
  await dialog.getByRole('button', { name: 'Lưu chấm công', exact: true }).click()
  const data = (await stored(page)).payroll
  const employee = data.employees.find((row: any) => row.name === name)
  expect(data.attendance.filter((row: any) => row.employeeId === employee.id && row.date === `${month}-02`)).toHaveLength(1)
  expect(data.settings.employeeInsuranceRate).toBe(10)
  await page.getByRole('tab', { name: 'Bảng lương', exact: true }).click()
  await page.getByLabel('Tháng tính lương', { exact: true }).fill(month)
  await page.getByRole('button', { name: `Điều chỉnh lương ${name}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Thưởng (₫)', { exact: true }).fill('100000')
  await dialog.getByLabel('Tạm ứng (₫)', { exact: true }).fill('200000')
  await dialog.getByLabel('Khấu trừ khác (₫)', { exact: true }).fill('5000')
  await dialog.getByLabel('Thuế TNCN nhập tay (₫)', { exact: true }).fill('10000')
  await dialog.getByRole('button', { name: 'Lưu điều chỉnh', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const salaryRow = page.getByRole('row').filter({ hasText: name })
  await expect(salaryRow).toContainText('1.220.000')
  await page.getByRole('button', { name: `Chi tiết lương ${name}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('375.000')
  await expect(dialog).toContainText('60.000')
  await expect(dialog).toContainText('100.000')
  await page.screenshot({ path: testInfo.outputPath('payroll-detail.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Đóng chi tiết', exact: true }).click()
  await page.getByRole('button', { name: 'Chốt bảng lương', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Xác nhận chốt lương', exact: true }).click()
  await expect(page.getByRole('button', { name: `Điều chỉnh lương ${name}`, exact: true })).toBeDisabled()
  let snapshot = (await stored(page)).payroll.periods.find((period: any) => period.month === month)
  expect(snapshot.rows.find((row: any) => row.employeeId === employee.id)).toMatchObject({ ordinaryPay: 1000000, overtimePay: 375000, allowancePay: 60000, insurance: 100000, netPay: 1220000 })
  await page.getByRole('tab', { name: 'Chấm công', exact: true }).click()
  await expect(page.getByRole('button', { name: `Chấm công ${name}`, exact: true })).toBeDisabled()
  await page.getByRole('tab', { name: 'Nhân sự', exact: true }).click()
  await page.getByRole('button', { name: `Sửa ${name}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel(/^Mức lương \(/).fill('52000000')
  await dialog.getByRole('button', { name: 'Lưu nhân viên', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.reload()
  await page.getByRole('tab', { name: 'Bảng lương', exact: true }).click()
  await page.getByLabel('Tháng tính lương', { exact: true }).fill(month)
  await expect(page.getByRole('row').filter({ hasText: name })).toContainText('1.220.000')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Xuất bảng lương CSV', exact: true }).click()
  const download = await downloadPromise
  const csv = await readFile((await download.path())!, 'utf8')
  expect(csv).toContain(name)
  expect(csv).toContain('"1220000"')
  await page.getByRole('button', { name: 'Mở lại bảng lương', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Xác nhận mở lại', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: name })).toContainText('2.595.000')
  expect((await stored(page)).payroll.periods.some((period: any) => period.month === month)).toBe(false)
  await page.getByLabel('Tháng tính lương', { exact: true }).fill('2030-02')
  const emptyRow = page.getByRole('row').filter({ hasText: name })
  await expect(emptyRow.locator('td').nth(4)).toHaveText(/0\s*₫/)
})
