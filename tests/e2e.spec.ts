test('a stale second tab cannot overwrite the first tab saved customer', async ({ page, context }) => {
  await page.goto('/#customers')
  const second = await context.newPage()
  await second.goto('/#customers')
  for (const [tab, name] of [[page, 'Khách đã lưu ở tab A'], [second, 'Khách chưa lưu ở tab B']] as const) {
    await tab.getByRole('button', { name: 'Thêm khách hàng', exact: true }).click()
    const modal = tab.getByRole('dialog', { name: 'Thêm khách hàng', exact: true })
    await expect(modal).toBeVisible()
    await modal.getByLabel('Tên công ty / khách hàng *').fill(name)
    await modal.getByLabel('Người liên hệ *').fill('Nguyễn QA')
    await modal.getByLabel('Điện thoại *').fill('0901234567')
  }
  await page.getByRole('dialog', { name: 'Thêm khách hàng', exact: true }).getByRole('button', { name: 'Lưu khách hàng' }).click()
  await expect(page.getByRole('heading', { name: 'Khách đã lưu ở tab A' })).toBeVisible()
  const staleDialog = second.getByRole('dialog', { name: 'Thêm khách hàng', exact: true })
  await staleDialog.getByRole('button', { name: 'Lưu khách hàng' }).click()
  await expect(staleDialog.getByRole('alert')).toContainText('Dữ liệu đã thay đổi ở một tab khác')
  await expect(staleDialog.getByLabel('Tên công ty / khách hàng *')).toHaveValue('Khách chưa lưu ở tab B')
  const saved = await stored(second)
  expect(saved.customers.some((c: any) => c.name === 'Khách đã lưu ở tab A')).toBe(true)
  expect(saved.customers.some((c: any) => c.name === 'Khách chưa lưu ở tab B')).toBe(false)
  await second.reload()
  await expect(second.getByRole('heading', { name: 'Khách đã lưu ở tab A' })).toBeVisible()
  await second.close()
})
