import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const stored = async (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('xuong-viet.data.v1') || 'null'))

test('responsive routes, persisted theme, and mobile menu', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Tổng quan xưởng.' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: testInfo.outputPath('overview-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Chuyển chế độ tối' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('overview-dark.png'), fullPage: true })
  if (testInfo.project.name === 'mobile') {
    await page.getByRole('button', { name: 'Mở menu' }).click()
    await page.locator('nav').getByRole('button', { name: 'Kho vật tư' }).click()
    await expect(page.getByRole('heading', { name: 'Kho vật tư.' })).toBeVisible()
    await expect(page.locator('.sidebar-backdrop')).toHaveCount(0)
  }
  for (const [route, title] of [['orders', 'Đơn hàng.'], ['production', 'Tiến độ sản xuất.'], ['inventory', 'Kho vật tư.'], ['customers', 'Khách hàng.'], ['finance', 'Thu chi & công nợ.'], ['settings', 'Cài đặt & dữ liệu.']]) {
    await page.goto('/#' + route)
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
    expect(overflow, `outer page must not overflow on ${route}`).toBeLessThanOrEqual(1)
  }
  expect(errors).toEqual([])
})

test('create, edit, progress and reload an order', async ({ page }) => {
  await page.goto('/#orders')
  await page.getByRole('button', { name: 'Tạo đơn hàng', exact: true }).click()
  let modal = page.getByRole('dialog')
  await expect(modal).toHaveAccessibleName('Tạo đơn hàng mới')
  await modal.getByRole('combobox', { name: 'Khách hàng *', exact: true }).selectOption({ index: 1 })
  await modal.getByLabel('Tên chi tiết / sản phẩm *').fill('Trục kiểm thử QA')
  await modal.getByLabel('Số lượng *', { exact: true }).fill('12')
  await modal.getByLabel('Đơn giá (VNĐ) *').fill('100000')
  await modal.getByLabel('Ngày giao hàng *').fill('2027-01-15')
  await modal.getByRole('button', { name: 'Tạo đơn hàng', exact: true }).click()
  await expect(modal).toHaveAccessibleName('Chi tiết đơn hàng')
  await expect(modal.getByRole('heading', { name: 'Trục kiểm thử QA' })).toBeVisible()
  await modal.getByRole('button', { name: 'Chỉnh sửa đơn', exact: true }).click()
  await modal.getByLabel('Tên chi tiết / sản phẩm *').fill('Trục kiểm thử đã sửa')
  await modal.getByRole('button', { name: 'Lưu thay đổi' }).click()
  await modal.getByLabel('Công đoạn hiện tại').selectOption('machining')
  await modal.getByLabel('Đã hoàn thành (tối đa 12)').fill('5')
  await modal.getByRole('button', { name: 'Lưu', exact: true }).click()
  await modal.getByRole('button', { name: 'Đóng', exact: true }).click()
  await page.reload()
  const row = page.getByRole('row').filter({ hasText: 'Trục kiểm thử đã sửa' })
  await expect(row).toBeVisible()
  await expect(row).toContainText('Đang gia công')
  const data = await stored(page)
  expect(data.orders.find((o: any) => o.partName === 'Trục kiểm thử đã sửa')).toMatchObject({ quantity: 12, unitPrice: 100000, status: 'machining', completedQuantity: 5 })
})

test('inventory records in/out and explains overdraw inside the dialog', async ({ page }) => {
  await page.goto('/#inventory')
  const row = page.locator('tbody').first().getByRole('row').first()
  const original = Number((await row.locator('td').nth(2).innerText()).split(' ')[0])
  for (const [type, quantity, note] of [['in', '10', 'QA nhập vật tư'], ['out', '3', 'QA xuất vật tư']]) {
    await row.getByRole('button', { name: 'Nhập / Xuất' }).click()
    const modal = page.getByRole('dialog')
    await modal.getByLabel('Loại giao dịch').selectOption(type)
    await modal.getByLabel(/^Số lượng/).fill(quantity)
    await modal.getByLabel('Lý do / mã đơn liên quan').fill(note)
    await modal.getByRole('button', { name: 'Lưu giao dịch' }).click()
    await expect(modal).toHaveCount(0)
    await expect(page.getByRole('cell', { name: note, exact: true })).toBeVisible()
  }
  expect((await stored(page)).materials[0].stock).toBe(original + 7)
  await row.getByRole('button', { name: 'Nhập / Xuất' }).click()
  const modal = page.getByRole('dialog')
  await modal.getByLabel('Loại giao dịch').selectOption('out')
  await modal.getByLabel(/^Số lượng/).fill(String(original + 8))
  await modal.getByLabel('Lý do / mã đơn liên quan').fill('QA vượt tồn')
  await modal.getByRole('button', { name: 'Lưu giao dịch' }).click()
  await expect(modal.getByRole('alert')).toContainText('Không đủ tồn kho')
  expect((await stored(page)).materials[0].stock).toBe(original + 7)
})

