test('payment cannot exceed outstanding balance and full receipt clears debt', async ({ page }) => {
  await page.goto('/#finance')
  const row = page.getByRole('row').filter({ has: page.getByRole('button', { name: 'Thu tiền', exact: true }) }).first()
  const code = await row.locator('td').first().locator('strong').innerText()
  await row.getByRole('button', { name: 'Thu tiền', exact: true }).click()
  const modal = page.getByRole('dialog')
  const amount = modal.getByLabel('Số tiền thu thêm (VNĐ) *')
  const cap = Number(await amount.getAttribute('max'))
  await amount.fill(String(cap + 1))
  await modal.getByRole('button', { name: 'Xác nhận thu tiền' }).click()
  await expect(modal).toBeVisible()
  expect(await amount.evaluate((el: HTMLInputElement) => el.validity.rangeOverflow)).toBe(true)
  await amount.fill(String(cap))
  await modal.getByRole('button', { name: 'Xác nhận thu tiền' }).click()
  await expect(modal).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText('Đã thu đủ')
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText('Đã thu đủ')
})

test('JSON backup roundtrip, invalid import rejection and reset cancellation', async ({ page }) => {
  await page.goto('/#settings')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Sao lưu JSON' }).click()
  const download = await downloadPromise
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(backup.version).toBe(1)
  expect(backup.orders.length).toBeGreaterThan(0)
  const input = page.locator('input[type=file]')
  await input.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') })
  await expect(page.getByRole('alert')).toContainText('không đúng định dạng')
  backup.customers[0].name = 'Khách từ bản sao lưu QA'
  page.once('dialog', dialog => dialog.accept())
  await input.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  await expect(page.locator('.toast')).toContainText('Đã khôi phục dữ liệu')
  expect((await stored(page)).customers[0].name).toBe('Khách từ bản sao lưu QA')
  await page.getByRole('button', { name: 'Đặt lại dữ liệu mẫu', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Giữ dữ liệu' }).click()
  expect((await stored(page)).customers[0].name).toBe('Khách từ bản sao lưu QA')
  await page.goto('/#customers')
  await expect(page.getByRole('heading', { name: 'Khách từ bản sao lưu QA' })).toBeVisible()
})

