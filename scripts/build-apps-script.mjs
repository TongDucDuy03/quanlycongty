import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

// Keep the deployed server's business rules identical to local/import rules.
// Code.gs is a checked-in one-file deployment artifact; edit Backend.js or the
// TypeScript domain validators, then regenerate. --check never writes files.
const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: 'export { validateData } from "./src/domain.ts";',
    resolveDir: root,
    sourcefile: 'sheets-validation-entry.ts',
    loader: 'ts',
  },
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'QLCTValidation',
  platform: 'neutral',
  target: 'es2022',
  treeShaking: true,
  plugins: [{
    name: 'omit-unused-presentation-formatters',
    setup(builder) {
      builder.onLoad({ filter: /[\\/]src[\\/]domain\.ts$/ }, async ({ path }) => ({
        // Constructors are presentation-only. Marking them pure lets esbuild
        // omit unused formatters without changing any validation source/rules.
        contents: (await readFile(path, 'utf8')).replace(/\bnew Intl\.(NumberFormat|DateTimeFormat)\(/g, '/* @__PURE__ */ new Intl.$1('),
        loader: 'ts',
      }))
    },
  }],
  legalComments: 'none',
  charset: 'utf8',
})
const backend = (await readFile(resolve(root, 'google-apps-script/Backend.js'), 'utf8')).replace(/\r\n/g, '\n')
const auth = await build({
  absWorkingDir: root,
  stdin: {
    contents: 'export { pbkdf2 } from "@noble/hashes/pbkdf2"; export { sha256 } from "@noble/hashes/sha256"; export { hmac } from "@noble/hashes/hmac";',
    resolveDir: root,
    sourcefile: 'sheets-auth-entry.js',
  },
  bundle: true, write: false, format: 'iife', globalName: 'QLCTCrypto',
  platform: 'neutral', target: 'es2022', treeShaking: true, minify: true, legalComments: 'none', charset: 'utf8',
})
const generated = '// GENERATED by npm run build:apps-script. Do not edit this file directly.\n'
  + '// Includes strict workshop/payroll validation from src/domain.ts and src/payroll.ts.\n'
  + result.outputFiles[0].text.replace(/\r\n/g, '\n') + '\n' + auth.outputFiles[0].text.replace(/\r\n/g, '\n') + '\n' + backend
const destination = resolve(root, 'google-apps-script/Code.gs')
if (process.argv.includes('--check')) {
  const current = (await readFile(destination, 'utf8')).replace(/\r\n/g, '\n')
  if (current !== generated) {
    console.error('Apps Script artifact is outdated. Run npm run build:apps-script and commit Code.gs.')
    process.exitCode = 1
  } else console.log('Apps Script artifact matches its backend and domain sources.')
} else {
  await writeFile(destination, generated, 'utf8')
  console.log('Generated google-apps-script/Code.gs with shared strict validators.')
}
